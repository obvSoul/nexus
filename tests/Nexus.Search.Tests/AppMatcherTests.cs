using Nexus.Search;
using Xunit;

namespace Nexus.Search.Tests;

public class AppMatcherTests
{
    private static LaunchableApp App(string name) => new(name, name + "!App");

    private static readonly LaunchableApp[] Apps =
    [
        App("Visual Studio Code"), App("Discord"), App("Discord PTB"), App("Calculatrice"), App("Paint"),
        App("Windows PowerShell"), App("Code Blocks"), App("Éditeur du Registre"),
    ];

    private static List<string> Find(params string[] terms) => AppMatcher.Find(Apps, terms, 5).Select(a => a.Name).ToList();

    [Fact]
    public void The_shortest_name_starting_with_the_text_comes_first() => Assert.Equal(["Discord", "Discord PTB"], Find("disc"));

    [Fact]
    public void A_word_inside_the_name_is_found_after_a_name_that_starts_with_it()
    {
        Assert.Equal(["Code Blocks", "Visual Studio Code"], Find("code"));
    }

    [Fact]
    public void Initials_find_an_application() => Assert.Equal("Visual Studio Code", Find("vsc")[0]);

    [Fact]
    public void Accents_do_not_matter() => Assert.Equal("Éditeur du Registre", Find("editeur")[0]);

    [Fact]
    public void A_typo_is_tolerated() => Assert.Equal("Calculatrice", Find("calculatirce")[0]);

    [Fact]
    public void Every_word_must_match()
    {
        Assert.Equal(["Discord PTB"], Find("discord", "ptb"));
        Assert.Empty(Find("discord", "zzz"));
    }

    [Fact]
    public void A_single_letter_only_matches_the_start_of_a_word()
    {
        Assert.Contains("Paint", Find("p"));
        Assert.DoesNotContain("Calculatrice", Find("l"));
    }

    [Fact]
    public void The_number_of_results_is_limited() => Assert.Single(AppMatcher.Find(Apps, ["disc"], 1));

    [Theory]
    [InlineData("Discord", "com.squirrel.Discord.Discord", true)]
    [InlineData("Warframe", "steam://rungameid/230410", true)]
    [InlineData("Revo Uninstaller", @"{6D809377-6AF0-444B-8957-A3773F02200E}\VS Revo Group\Revo Uninstaller\RevoUnin.exe", true)]
    [InlineData("Steam Support Center", "http://support.steampowered.com/", false)]
    [InlineData("Lisez-moi", @"{7C5A40EF-A0FB-4BFC-874A-C0F2E0B9FA8E}\LARP\Locale\Documents\LisezMoi.txt", false)]
    [InlineData("Désinstaller Revo", @"{6D809377-6AF0-444B-8957-A3773F02200E}\Revo\unins000.exe", false)]
    [InlineData("Uninstall Node.js", "Microsoft.AutoGenerated.{3A508491}", false)]
    [InlineData("Driver", @"C:\Driver\unins000.exe", false)]
    public void Links_manuals_and_uninstallers_are_not_applications(string name, string target, bool expected) =>
        Assert.Equal(expected, AppMatcher.IsLaunchable(name, target));
}
